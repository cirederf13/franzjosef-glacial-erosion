#!/usr/bin/env python3
"""Write a resume config for a glacial-cycle run that stopped part-way, from its last clean (non-NaN) snapshot.

Usage: python make_restart.py <failed_output.nc> <base_experiment_name> [--out-yaml NAME]
"""
import argparse
import os
import re
import sys

import numpy as np
import xarray as xr

MAX_PLAUSIBLE_KM3 = 5000.0     # Franz Josef catchment; LGM peak is ~300 km3


def last_clean_snapshot(nc, dx=77.875, dy=78.0):
    ds = xr.open_dataset(nc)
    t = ds.time.values
    best = None
    for i in range(len(t) - 1, -1, -1):
        thk = ds.thk.values[i]
        if not np.all(np.isfinite(thk)):
            continue
        vol = float(np.nansum(thk)) * dx * dy / 1e9
        if not np.isfinite(vol) or vol > MAX_PLAUSIBLE_KM3 or vol < 0:
            continue
        # also require the velocity field to be clean, not just thickness
        vb = ds.velbase_mag.values[i]
        if not np.all(np.isfinite(vb)):
            continue
        best = (i, float(t[i]), vol)
        break
    ds.close()
    return best, len(t)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('nc')
    ap.add_argument('base', help='experiment name to resume, without .yaml')
    ap.add_argument('--out-yaml')
    a = ap.parse_args()

    best, ntot = last_clean_snapshot(a.nc)
    if best is None:
        sys.exit('ERROR: no clean snapshot found in ' + a.nc)
    i, tstart, vol = best
    print(f"# {a.nc}")
    print(f"# snapshots present: {ntot}; last CLEAN one is index {i} "
          f"at t={tstart:.1f} yr, volume {vol:.2f} km3")
    if i < ntot - 1:
        print(f"# NOTE: {ntot-1-i} later snapshot(s) were rejected as NaN/implausible "
              f"-- typical of a blown-up run that kept writing after it died.")

    base_path = f'experiment/{a.base}.yaml'
    src = open(base_path).read()

    # swap the input from load_tif to load_ncdf, pointed at the failed run
    src = re.sub(r'(  - override /inputs:\n)(?:    - \S+\n)+',
                 r'\1    - load_ncdf\n', src)
    folder = os.path.dirname(os.path.abspath(a.nc))
    infile = os.path.basename(a.nc)
    src = re.sub(r'\ninputs:\n(?:  \S[^\n]*\n|    [^\n]*\n)+',
                 f'\ninputs:\n  load_ncdf:\n    input_file: {infile}\n    coarsen: 1\n',
                 src, count=1)
    # core.folder_data must point at the directory holding the restart file
    if re.search(r'^core:', src, re.M):
        src = re.sub(r'^core:\n', f'core:\n  folder_data: {folder}\n', src, count=1, flags=re.M)
    else:
        src = src.replace('\ninputs:\n', f'\ncore:\n  folder_data: {folder}\n\ninputs:\n', 1)
    # start time = the clean snapshot; load_ncdf matches it exactly (float32), which relies on NumPy 1.x casting
    src = re.sub(r'(\n    start: )[-\d.]+', rf'\g<1>{tstart:.1f}', src, count=1)

    banner = (f"# ===================== AUTO-GENERATED RESTART =====================\n"
              f"# Resumes {a.base} from a saved snapshot instead of from scratch.\n"
              f"# Source run : {a.nc}\n"
              f"# Restart at : t = {tstart:.1f} yr (ice volume {vol:.2f} km3),\n"
              f"#              the LAST CLEAN snapshot -- {ntot-1-i} later snapshot(s)\n"
              f"#              were rejected as NaN/implausible.\n"
              f"# Generated by make_restart.py. Physics/forcing are inherited\n"
              f"# unchanged from {a.base}.yaml; only inputs (load_tif -> load_ncdf),\n"
              f"# core.folder_data and time.start differ.\n"
              f"# =================================================================\n")
    out = a.out_yaml or f'{a.base}_restart'
    dst = f'experiment/{out}.yaml'
    lines = src.split('\n')
    if lines and lines[0].strip().startswith('# @package'):
        src = lines[0] + '\n' + banner + '\n'.join(lines[1:])
    else:
        src = banner + src
    open(dst, 'w').write(src)
    print(f"\nwrote {dst}")
    print(f"\nlaunch with:\n  igm_run +experiment={out}")


if __name__ == '__main__':
    main()
